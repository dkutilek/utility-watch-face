#!/usr/bin/env python3
"""Generates the watch face definition, weather icons and picker preview.

Run through build.sh. Requires Pillow for the images:
    python3 tools/generate.py

Outputs into res/:
    raw/watchface.xml      the face itself (Watch Face Format)
    drawable-nodpi/*.png   weather icons, white on transparent so they can be tinted
    drawable-nodpi/preview.png   thumbnail shown in the watch face picker
"""
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "res"

# --- Layout, in the 450x450 coordinate space the format scales to either watch size.
SIZE = 450
DATE_Y, DATE_H, DATE_SIZE = 66, 52, 30
TIME_Y, TIME_H, TIME_SIZE = 138, 170, 140
WEATHER_Y, WEATHER_H = 322, 64
ICON_X, ICON_SIZE = 157, 46
TEMP_X, TEMP_SIZE = 213, 38

THEMES = [
    ("mint", "Mint", "#FF9CF0B4"),
    ("sky", "Sky", "#FF9BD3FF"),
    ("amber", "Amber", "#FFFFD27A"),
    ("rose", "Rose", "#FFFFB0C4"),
    ("lavender", "Lavender", "#FFCDB9FF"),
    ("white", "White", "#FFFFFFFF"),
]

# WEATHER.CONDITION value -> icon, in enum order 0..15. Index 14 and 1 differ by day/night.
CONDITION_ICONS = [
    "ic_wx_unknown", "ic_wx_sun", "ic_wx_cloud", "ic_wx_fog", "ic_wx_heavy_rain",
    "ic_wx_heavy_snow", "ic_wx_rain", "ic_wx_snow", "ic_wx_sun", "ic_wx_storm",
    "ic_wx_sleet", "ic_wx_snow", "ic_wx_rain", "ic_wx_fog", "ic_wx_partly_day", "ic_wx_wind",
]


def bitmap_font(name, night):
    lines = [f'    <BitmapFont name="{name}">']
    for code, icon in enumerate(CONDITION_ICONS):
        if night and code in (1, 8):
            icon = "ic_wx_moon"
        if night and code == 14:
            icon = "ic_wx_partly_night"
        tag = "Character" if code < 10 else "Word"
        lines.append(f'      <{tag} name="{code}" resource="{icon}" width="96" height="96" />')
    lines.append("    </BitmapFont>")
    return "\n".join(lines)


def text_part(x, y, width, height, size, align, template, params, color, name):
    parameters = "".join(f'<Parameter expression="{p}" />' for p in params)
    return f"""<PartText x="{x}" y="{y}" width="{width}" height="{height}" name="{name}">
            <Variant mode="AMBIENT" target="alpha" value="200" />
            <Text align="{align}" ellipsis="TRUE">
              <Font family="SYNC_TO_DEVICE" size="{size}" weight="MEDIUM" color="{color}">
                <Template><![CDATA[{template}]]>{parameters}</Template>
              </Font>
            </Text>
          </PartText>"""


def weather_icon(family):
    return f"""<PartText x="{ICON_X}" y="{WEATHER_Y + (WEATHER_H - ICON_SIZE) // 2}" width="{ICON_SIZE}" height="{ICON_SIZE}" tintColor="[CONFIGURATION.themeColor]">
                <Text>
                  <BitmapFont family="{family}" size="{ICON_SIZE}">
                    <Template><![CDATA[%s]]><Parameter expression="[WEATHER.CONDITION] &lt;= 15 ? [WEATHER.CONDITION] : 0" /></Template>
                  </BitmapFont>
                </Text>
              </PartText>"""


def build_face():
    options = "\n".join(
        f'      <ColorOption id="{i}" displayName="color_{tid}" colors="{color}" />'
        for i, (tid, _, color) in enumerate(THEMES)
    )
    unit = "[WEATHER.TEMPERATURE_UNIT] == 2 ? &quot;F&quot; : &quot;C&quot;"
    date = text_part(40, DATE_Y, SIZE - 80, DATE_H, DATE_SIZE, "CENTER", "%s %s %d",
                     ["[DAY_OF_WEEK_S]", "[MONTH_S]", "[DAY]"], "#FFFFFFFF", "date")
    temp = text_part(TEMP_X, WEATHER_Y, SIZE - TEMP_X - 40, WEATHER_H, TEMP_SIZE, "START", "%d°%s",
                     ["[WEATHER.TEMPERATURE]", unit], "#FFFFFFFF", "temperature")
    unavailable = text_part(40, WEATHER_Y, SIZE - 80, WEATHER_H, 28, "CENTER", "%s",
                            ["&quot;Weather unavailable&quot;"], "#FFFFFFFF", "no_weather")
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/generate.py. Edit that file, not this one. -->
<WatchFace width="{SIZE}" height="{SIZE}" clipShape="CIRCLE">
  <Metadata key="CLOCK_TYPE" value="DIGITAL" />
  <Metadata key="PREVIEW_TIME" value="10:08:32" />
  <BitmapFonts>
{bitmap_font("wx_day", night=False)}
{bitmap_font("wx_night", night=True)}
  </BitmapFonts>
  <UserConfigurations>
    <ColorConfiguration id="themeColor" displayName="color_label" defaultValue="0">
{options}
    </ColorConfiguration>
  </UserConfigurations>
  <Scene backgroundColor="#FF000000">
    <Group name="date_line" x="0" y="0" width="{SIZE}" height="{SIZE}">
          {date}
    </Group>
    <DigitalClock x="0" y="{TIME_Y}" width="{SIZE}" height="{TIME_H}">
      <TimeText format="h:mm" hourFormat="SYNC_TO_DEVICE" align="CENTER" x="0" y="0" width="{SIZE}" height="{TIME_H}">
        <Font family="SYNC_TO_DEVICE" size="{TIME_SIZE}" weight="MEDIUM" color="[CONFIGURATION.themeColor]" />
      </TimeText>
    </DigitalClock>
    <Group name="weather_line" x="0" y="0" width="{SIZE}" height="{SIZE}">
      <Condition>
        <Expressions>
          <Expression name="has_weather">[WEATHER.IS_AVAILABLE]</Expression>
        </Expressions>
        <Compare expression="has_weather">
          <Group name="weather" x="0" y="0" width="{SIZE}" height="{SIZE}">
          {temp}
            <Condition>
              <Expressions>
                <Expression name="daytime">[WEATHER.IS_DAY]</Expression>
              </Expressions>
              <Compare expression="daytime">
              {weather_icon("wx_day")}
              </Compare>
              <Default>
              {weather_icon("wx_night")}
              </Default>
            </Condition>
          </Group>
        </Compare>
        <Default>
          {unavailable}
        </Default>
      </Condition>
    </Group>
  </Scene>
</WatchFace>
"""


def build_strings():
    names = [("watch_face_name", "Utility Classic"), ("color_label", "Color")]
    names += [(f"color_{tid}", label) for tid, label, _ in THEMES]
    body = "\n".join(f'  <string name="{k}">{v}</string>' for k, v in names)
    return f'<?xml version="1.0" encoding="utf-8"?>\n<resources>\n{body}\n</resources>\n'


# --- Icons. Drawn 4x oversize and scaled down for clean edges.
ICON = 96
S = 4


def canvas():
    img = Image.new("L", (ICON * S, ICON * S), 0)
    return img, ImageDraw.Draw(img)


def p(v):
    return int(round(v * S))


def circle(d, x, y, r, fill=255):
    d.ellipse([p(x - r), p(y - r), p(x + r), p(y + r)], fill=fill)


def stroke(d, x1, y1, x2, y2, w=7, fill=255):
    d.line([p(x1), p(y1), p(x2), p(y2)], fill=fill, width=p(w))
    circle(d, x1, y1, w / 2, fill)
    circle(d, x2, y2, w / 2, fill)


def sun(d, x, y, r, ray=9, gap=6, w=6):
    circle(d, x, y, r)
    for i in range(8):
        a = math.radians(45 * i)
        inner, outer = r + gap, r + gap + ray
        stroke(d, x + inner * math.cos(a), y + inner * math.sin(a),
               x + outer * math.cos(a), y + outer * math.sin(a), w)


def moon(d, x, y, r):
    circle(d, x, y, r)
    circle(d, x + r * 0.55, y - r * 0.3, r * 0.82, 0)


def cloud(d, x=48, y=46, scale=1.0, cut=0):
    """Rounded cloud. `cut` paints a dark outline first so it reads over another shape."""
    parts = [(-20, 8, 14), (0, -6, 20), (21, 6, 15)]
    box = [-20, 8, 21, 22]
    for fill, grow in ((0, cut), (255, 0)):
        if fill == 0 and not cut:
            continue
        for dx, dy, r in parts:
            circle(d, x + dx * scale, y + dy * scale, (r + grow) * scale, fill)
        d.rectangle([p(x + (box[0] - grow) * scale), p(y + box[1] * scale),
                     p(x + (box[2] + grow) * scale), p(y + (box[3] + grow) * scale)], fill=fill)


def icon_sun(d):
    sun(d, 48, 48, 19)


def icon_moon(d):
    moon(d, 46, 50, 32)


def icon_cloud(d):
    cloud(d, 48, 44, 1.2)


def icon_partly_day(d):
    sun(d, 62, 32, 13, ray=7, gap=5, w=5)
    cloud(d, 42, 56, 1.0, cut=6)


def icon_partly_night(d):
    moon(d, 62, 32, 19)
    cloud(d, 42, 58, 1.0, cut=6)


def drops(d, xs, y=72, length=14, w=6):
    for x in xs:
        stroke(d, x + 3, y, x - 3, y + length, w)


def flakes(d, xs, y=78, r=5):
    for x in xs:
        circle(d, x, y, r)


def icon_rain(d):
    cloud(d, 48, 32)
    drops(d, (34, 62))


def icon_heavy_rain(d):
    cloud(d, 48, 32)
    drops(d, (26, 48, 70))


def icon_snow(d):
    cloud(d, 48, 32)
    flakes(d, (34, 62))


def icon_heavy_snow(d):
    cloud(d, 48, 32)
    flakes(d, (26, 48, 70))


def icon_sleet(d):
    cloud(d, 48, 32)
    drops(d, (30,))
    flakes(d, (62,))


def icon_storm(d):
    cloud(d, 48, 30)
    d.polygon([(p(x), p(y)) for x, y in [(52, 54), (34, 74), (47, 74), (40, 92), (62, 68), (49, 68)]], fill=255)


def icon_fog(d):
    for y, a, b in ((26, 18, 78), (42, 10, 70), (58, 26, 86), (74, 18, 66)):
        stroke(d, a, y, b, y, 7)


def icon_wind(d):
    # Three gusts, each a straight line ending in an upward or downward curl.
    d.arc([p(50), p(14), p(76), p(40)], 150, 90, fill=255, width=p(7))
    stroke(d, 63, 37, 10, 37, 7)
    stroke(d, 10, 52, 74, 52, 7)
    d.arc([p(62), p(52), p(88), p(78)], 270, 180, fill=255, width=p(7))
    stroke(d, 18, 67, 42, 67, 7)
    d.arc([p(34), p(64), p(58), p(88)], 270, 180, fill=255, width=p(7))


def icon_unknown(d):
    d.arc([p(30), p(14), p(66), p(50)], 180, 60, fill=255, width=p(9))
    stroke(d, 58, 46, 48, 58, 9)
    circle(d, 48, 78, 6)


ICONS = {
    "ic_wx_sun": icon_sun, "ic_wx_moon": icon_moon, "ic_wx_cloud": icon_cloud,
    "ic_wx_partly_day": icon_partly_day, "ic_wx_partly_night": icon_partly_night,
    "ic_wx_rain": icon_rain, "ic_wx_heavy_rain": icon_heavy_rain, "ic_wx_snow": icon_snow,
    "ic_wx_heavy_snow": icon_heavy_snow, "ic_wx_sleet": icon_sleet, "ic_wx_storm": icon_storm,
    "ic_wx_fog": icon_fog, "ic_wx_wind": icon_wind, "ic_wx_unknown": icon_unknown,
}


def render_icon(draw_fn):
    mask, d = canvas()
    draw_fn(d)
    mask = mask.resize((ICON, ICON), Image.LANCZOS)
    img = Image.new("RGBA", (ICON, ICON), (255, 255, 255, 0))
    img.putalpha(mask)
    return img


def build_preview(out):
    """A static thumbnail for the picker, drawn to match the live layout."""
    mint = (0x9C, 0xF0, 0xB4, 255)
    white = (255, 255, 255, 255)
    img = Image.new("RGBA", (SIZE * 2, SIZE * 2), (0, 0, 0, 255))
    d = ImageDraw.Draw(img)
    font = "/System/Library/Fonts/HelveticaNeue.ttc"
    centre = lambda y, h: (y + h / 2) * 2
    d.text((SIZE, centre(DATE_Y, DATE_H)), "Sat Nov 7",
           font=ImageFont.truetype(font, DATE_SIZE * 2, index=10), fill=white, anchor="mm")
    d.text((SIZE, centre(TIME_Y, TIME_H)), "10:08",
           font=ImageFont.truetype(font, TIME_SIZE * 2, index=10), fill=mint, anchor="mm")
    d.text((TEMP_X * 2, centre(WEATHER_Y, WEATHER_H)), "58°F",
           font=ImageFont.truetype(font, TEMP_SIZE * 2, index=10), fill=white, anchor="lm")
    tinted = Image.new("RGBA", (ICON_SIZE * 2, ICON_SIZE * 2), mint)
    tinted.putalpha(render_icon(icon_partly_day).getchannel("A").resize(tinted.size, Image.LANCZOS))
    img.alpha_composite(tinted, (ICON_X * 2, (WEATHER_Y + (WEATHER_H - ICON_SIZE) // 2) * 2))
    img.convert("RGB").resize((SIZE, SIZE), Image.LANCZOS).save(out)


def main():
    (RES / "raw").mkdir(parents=True, exist_ok=True)
    (RES / "values").mkdir(parents=True, exist_ok=True)
    drawable = RES / "drawable-nodpi"
    drawable.mkdir(parents=True, exist_ok=True)
    (RES / "raw" / "watchface.xml").write_text(build_face(), encoding="utf-8")
    (RES / "values" / "strings.xml").write_text(build_strings(), encoding="utf-8")
    for name, fn in ICONS.items():
        render_icon(fn).save(drawable / f"{name}.png")
    build_preview(drawable / "preview.png")


if __name__ == "__main__":
    main()
